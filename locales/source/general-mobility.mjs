export function generalMobilityMessages(locale) {
  const row = rows[locale];
  if (!row) throw Error("Missing General mobility locale " + locale);
  const keys = [
    "branch.general",
    "skill.general-sprint.name",
    "skill.general-double-dash.name",
    "ui.generalMobilityHelp",
    "ui.sprint",
    "ui.sprintRest",
    "skill.general-sprint.description",
    "skill.general-double-dash.description",
    "stat.sprintUnlock",
    "stat.dodgeCharges",
  ];
  if (row.length !== keys.length) throw Error("General mobility locale shape");
  return Object.fromEntries(
    keys.map((key, i) => [key, row[i].normalize("NFC")]),
  );
}
