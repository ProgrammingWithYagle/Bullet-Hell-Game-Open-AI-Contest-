export function bardMessages(language, c, existing) {
  const r = rows[language],
    a = contracts[language],
    weapons = weaponNames[language];
  if (!r || !a || !weapons) throw Error("Missing Bard edition " + language);
  const cl = c.classes.find((cl) => cl.id === "bard"),
    out = {
      "class.bard.name": r[0],
      "class.bard.role": r[1],
      "class.bard.lore": r[2],
      "ability.bard-q.name": r[3],
      "ability.bard-e.name": r[4],
      "ability.bard-ultimate.name": r[5],
      "ability.bard-q.description": a[0],
      "ability.bard-e.description": a[1],
      "ability.bard-ultimate.description": a[2],
      "branch.notecraft": r[6],
      "branch.performance": r[7],
      "branch.company": r[8],
      "ui.bardCadence": r[9],
      "stat.phraseRadius": r[10],
    };
  for (const [i, talent] of [
    "held-note",
    "travelling-chorus",
    "borrowed-cue",
  ].entries()) {
    out["talent." + talent + ".name"] = r[11 + i * 2];
    out["talent." + talent + ".description"] = r[12 + i * 2];
  }
  for (const [tier, name] of weapons.entries()) {
    out["weapon.bard-" + tier + ".name"] = name;
    out["weapon.bard-" + tier + ".description"] =
      existing["weapon.soldier-0.description"];
  }
  for (const s of c.skills.filter((s) => s.classId === "bard")) {
    const branch = cl.branches.findIndex((b) => b.id === s.branchId),
      focus = s.lane
        ? (out[s.subbranchNameKey] ?? existing[s.subbranchNameKey])
        : "";
    out["skill." + s.id + ".name"] = s.transform
      ? out["talent." + s.transform + ".name"]
      : language === "en"
        ? s.name
        : r[6 + branch] + " " + s.depth + (focus ? " · " + focus : "");
    out["skill." + s.id + ".description"] =
      existing["skill.soldier-command-1.description"];
  }
  return out;
}
