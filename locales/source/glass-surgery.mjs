export function glassSurgeryMessages(locale) {
  const row = rows[locale];
  if (!row || row.length !== 11)
    throw Error("Glass Surgery locale shape " + locale);
  const keys = [
    ...Array.from({ length: 4 }, (_, i) => "boss.glass-surgeon.phase." + i),
    ...Array.from({ length: 4 }, (_, i) => "boss.glass-surgeon.phaseHint." + i),
    "boss.glass-surgeon.brutalHelp",
    "boss.glass-surgeon.crazedHelp",
    "boss.glass-surgeon.lore",
  ];
  const result = Object.fromEntries(
    keys.map((key, i) => [key, row[i].normalize("NFC")]),
  );
  result["boss.glass-surgeon.description"] = row
    .slice(4, 7)
    .join(" ")
    .normalize("NFC");
  return result;
}
