export function stationSignalsMessages(locale) {
  const row = rows[locale];
  if (!row || row.length !== 11)
    throw Error("Station Signals locale " + locale);
  const keys = [
    ...Array.from({ length: 4 }, (_, i) => "boss.stationmaster.phase." + i),
    ...Array.from({ length: 4 }, (_, i) => "boss.stationmaster.phaseHint." + i),
    "boss.stationmaster.brutalHelp",
    "boss.stationmaster.crazedHelp",
    "boss.stationmaster.lore",
  ];
  const values = row.map((v) => v.normalize("NFC"));
  return {
    ...Object.fromEntries(keys.map((key, i) => [key, values[i]])),
    "boss.stationmaster.description": values.slice(4, 7).join(" "),
  };
}
