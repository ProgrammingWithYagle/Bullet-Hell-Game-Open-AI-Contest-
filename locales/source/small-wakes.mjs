const ids = ["candle-snail", "cobble-crab", "mourning-kettle"];
export function smallWakesMessages(locale) {
  const r = rows[locale];
  if (!r || r.length !== 3 || r.some((x) => x.length !== 6))
    throw Error("Missing Small Wakes help " + locale);
  return Object.fromEntries(
    r.flatMap((row, i) => {
      const [name, a, b, c, d, e] = row.map((s) => s.normalize("NFC"));
      const k = "boss." + ids[i];
      return [
        [k + ".name", name],
        [k + ".phase.0", a],
        [k + ".phase.1", b],
        [k + ".phaseHint.0", c],
        [k + ".phaseHint.1", d],
        [k + ".description", c + " " + d],
        [k + ".brutalHelp", e],
      ];
    }),
  );
}
