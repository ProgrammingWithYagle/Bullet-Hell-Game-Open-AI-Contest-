export function playHubsMessages(locale) {
  const row = rows[locale];
  if (!row || row.length !== keys.length)
    throw Error("Play hubs locale " + locale);
  return {
    ...storyReadyMessages(locale),
    ...Object.fromEntries(
      keys.map((key, i) => ["ui." + key, row[i].normalize("NFC")]),
    ),
    "ui.newRun": row[0],
  };
}
