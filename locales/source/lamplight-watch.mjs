export function lamplightWatchMessages(locale) {
  const row = rows[locale];
  if (!row || row.length !== 11)
    throw Error("Lamplight Watch locale " + locale);
  const keys = [
    ...Array.from({ length: 4 }, (_, i) => "boss.lamplighter.phase." + i),
    ...Array.from({ length: 4 }, (_, i) => "boss.lamplighter.phaseHint." + i),
    "boss.lamplighter.brutalHelp",
    "boss.lamplighter.crazedHelp",
    "boss.lamplighter.lore",
  ];
  const values = row.map((v) => v.normalize("NFC"));
  return {
    ...Object.fromEntries(keys.map((key, i) => [key, values[i]])),
    "boss.lamplighter.description": values.slice(4, 7).join(" "),
  };
}
