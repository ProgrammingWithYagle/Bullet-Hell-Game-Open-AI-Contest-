export function sluicePressureMessages(locale) {
  const row = rows[locale];
  if (!row || row.length !== 11)
    throw Error("Sluice Pressure locale " + locale);
  const keys = [
    ...Array.from({ length: 4 }, (_, i) => "boss.sluice-keeper.phase." + i),
    ...Array.from({ length: 4 }, (_, i) => "boss.sluice-keeper.phaseHint." + i),
    "boss.sluice-keeper.brutalHelp",
    "boss.sluice-keeper.crazedHelp",
    "boss.sluice-keeper.lore",
  ];
  const values = row.map((v) =>
    v
      .replace(/(\p{L})(5\.1|10\.2|90)/gu, "$1 $2")
      .replace(/(5\.1|10\.2|90)(\p{L})/gu, "$1 $2")
      .normalize("NFC"),
  );
  return {
    ...Object.fromEntries(keys.map((key, i) => [key, values[i]])),
    "boss.sluice-keeper.description": values.slice(4, 7).join(" "),
  };
}
