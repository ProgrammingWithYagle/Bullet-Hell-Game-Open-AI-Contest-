export function bakerOvenMessages(locale) {
  const row = rows[locale];
  if (!row || row.length !== 11) throw Error("Baker Oven locale " + locale);
  const keys = [
    ...Array.from({ length: 4 }, (_, i) => "boss.ash-baker.phase." + i),
    ...Array.from({ length: 4 }, (_, i) => "boss.ash-baker.phaseHint." + i),
    "boss.ash-baker.brutalHelp",
    "boss.ash-baker.crazedHelp",
    "boss.ash-baker.lore",
  ];
  const values = row.map((value) =>
    value
      .replace(/(\p{L})([47]\.\d)/gu, "$1 $2")
      .replace(/([47]\.\d)(\p{L})/gu, "$1 $2")
      .normalize("NFC"),
  );
  return {
    ...Object.fromEntries(keys.map((key, i) => [key, values[i]])),
    "boss.ash-baker.description": values.slice(4, 7).join(" "),
  };
}
