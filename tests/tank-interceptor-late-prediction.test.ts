import assert from 'node:assert/strict';
import { test } from 'node:test';
import { interceptionFixture, point } from './helpers/tank-interceptor-fixture.ts';
import { interceptorIds } from '../src/shared/tank-interceptor.ts';
import { viewOf } from '../src/shared/view.ts';
import { idleInput } from '../src/shared/protocol.ts';
import { tankInterceptionInput, tankInterceptionSpeed, tankInterceptionAfterMove } from '../src/client/tank-interceptor-prediction.ts';

test('the owner sees return readiness while the peer sees only the existing finite screen', () => {
  const f = interceptionFixture({ choice:'crossing', extra:[interceptorIds.returns], ally:true });
  const state = f.launch(0,1);
  for(let n=0;n<5;n++)f.step();
  const {g,p,peer} = f;
  const acknowledged = viewOf(g,p.id);
  const owner = acknowledged.players.find(player=>player.id===p.id)!;
  const foreign = viewOf(g,peer!.id);
  assert(owner.kit.interceptorCanReturn);
  assert(!Object.hasOwn(foreign.players.find(player=>player.id===p.id)!.kit,'interceptorCanReturn'));
  const projected=structuredClone(owner), before=point(owner);
  const next = { technique3:true,moveY:-1 };
  const originalMotion=projected.dashY;
  tankInterceptionInput(projected,{...idleInput(),...next},g.combatTick+1);
  assert.equal(tankInterceptionSpeed(projected,g.combatTick+1),0);
  assert.equal(projected.kit.interceptorPhase,'screen');
  assert.equal(projected.dashY,originalMotion);
  assert.deepEqual(point(projected),before);
  assert.deepEqual(point(owner),before);
  assert.equal(projected.eAt,owner.eAt);
  const events=f.step(next);
  assert(f.status()?.returned);
  assert(f.status()?.until===state.until);
  assert(events.some(event=>event.type==='sound'&&event.id==='tank-intercept-return'&&event.owner===p.id));
  const confirmed=viewOf(g,p.id).players.find(player=>player.id===p.id)!;
  assert(confirmed.dashY<0);
  assert.equal(tankInterceptionSpeed(confirmed,g.combatTick+1),600);
});

test('offset input preserves an acknowledged held brace without predicting a screen before launch', () => {
  const f = interceptionFixture({choice:'standfast',extra:[interceptorIds.offset],ally:true});
  f.arm(0);
  const {g,p}=f;
  const kit=viewOf(g,p.id).players.find(player=>player.id===p.id)!;
  assert(kit.kit.interceptorCanOffsetLeft&&kit.kit.interceptorCanOffsetRight);
  const direction={moveY:1,technique3:true};
  const ready=structuredClone(kit);
  const input=tankInterceptionInput(ready,{...idleInput(),...direction},g.combatTick+1);
  assert.equal(input.moveY,0);
  assert.equal(ready.kit.interceptorPhase,'ready');
  assert(!g.classCues().some(cue=>cue.kind==='tank-intercept-screen'));
  const launched=f.step(direction);
  assert(launched.some(event=>event.type==='sound'&&event.id==='tank-intercept-offset'&&event.owner===p.id));
  const owner=viewOf(g,p.id).players.find(player=>player.id===p.id)!;
  const observer=viewOf(g,f.peer!.id).players.find(player=>player.id===p.id)!;
  assert.equal(owner.kit.interceptorOffset,56);
  assert.equal(owner.kit.interceptorOffsetHeld,56);
  assert(!Object.hasOwn(observer.kit,'interceptorOffset'));
  const nextTick=g.combatTick+1;
  const projected=structuredClone(owner);
  tankInterceptionInput(projected,{...idleInput(),...direction},nextTick);
  assert.equal(projected.kit.interceptorPhase,'screen');
  assert.equal(tankInterceptionSpeed(projected,nextTick),0);
  tankInterceptionAfterMove(projected,point(projected),{...f.arena,playerRadius:18,tick:nextTick});
  assert.equal(projected.kit.interceptorPhase,'screen');
  tankInterceptionInput(projected,idleInput(),nextTick+1);
  tankInterceptionInput(projected,{...idleInput(),moveY:1},nextTick+2);
  assert.equal(projected.kit.interceptorPhase,'idle');
});
