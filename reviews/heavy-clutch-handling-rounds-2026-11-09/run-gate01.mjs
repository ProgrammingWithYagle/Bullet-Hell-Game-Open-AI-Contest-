if (result.exitCode !== 0 && fs.existsSync(root + '/reviews/runtime-verification.json')) fs.copyFileSync(root + '/reviews/runtime-verification.json', stage + '/gate01-runtime-failure.json', fs.constants.COPYFILE_EXCL);
console.log(JSON.stringify(report));
process.exitCode = result.exitCode ?? 1;
