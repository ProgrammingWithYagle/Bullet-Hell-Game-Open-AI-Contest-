const report = { checkedAt: new Date().toISOString(), ...result, elapsedMs: Date.now() - start, log, localTestingEndpoint: 'http://127.0.0.1:2752', newPortsAvailableByActualExclusiveBind: true, expectedTests: 2149, allExistingChecksAndTimeoutsRetained: true };
