import fs from 'node:fs';
import path from 'node:path';
import net from 'node:net';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
const stage = path.dirname(fileURLToPath(import.meta.url));
const root = 'C:/Users/yigal/OneDrive/Documents/ChatGPT/OpenAI Multiplayer Game Contest (Bullet Hell)';
const admission = JSON.parse(fs.readFileSync(stage + '/admission01.json', 'utf8'));
assert(admission.expectedTests === 2149 && !admission.gameplayAndContentChanges && !admission.sourceBearingProgressRegenerated);
for (const port of [5376, 2752, 5377, 2753]) await new Promise((resolve, reject) => { const server = net.createServer(); server.once('error', reject); server.listen({ host: '127.0.0.1', port, exclusive: true }, () => server.close(resolve)); });
const log = stage + '/gate01.log', fd = fs.openSync(log, 'wx'), start = Date.now();
const child = spawn(process.execPath, ['tools/verify.mjs'], { cwd: root, env: { ...process.env, VITE_GAME_AUDIENCE: 'testing', VITE_GAME_SERVER: 'http://127.0.0.1:2752' }, stdio: ['ignore', fd, fd] });
console.log(JSON.stringify({ startedAllSevenChecks: true, expectedTests: 2149, log, noTimeoutsChanged: true }));
const result = await new Promise(resolve => { child.once('error', error => resolve({ exitCode: null, error: String(error) })); child.once('exit', exitCode => resolve({ exitCode })); });
